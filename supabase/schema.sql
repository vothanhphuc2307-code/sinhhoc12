create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  student_id text not null,
  test_id integer not null check (test_id between 1 and 24),
  score numeric(3,1) not null check (score >= 0 and score <= 10),
  correct_count integer not null,
  total_questions integer not null default 10,
  diagnostics jsonb not null default '{}'::jsonb,
  responses jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists quiz_attempts_student_created_idx
  on public.quiz_attempts (student_id, created_at desc);
-- Optional defense in depth: client-side anon users should not directly read or write this table.
alter table public.quiz_attempts enable row level security;
